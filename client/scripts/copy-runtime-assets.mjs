// Copies WASM runtimes and OCR assets from node_modules into public/ so that every AI
// component is served from our own origin (no CDN at runtime => works offline once cached).
// Runs automatically after `npm install`.
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pub = (...p) => join(root, "public", ...p);
const log = (m) => console.log(`[copy-runtime-assets] ${m}`);

/** Find a package directory the way Node does (walk up node_modules); works even when
 * the package's `exports` map hides package.json. */
function pkgDir(name, from = root) {
  for (let dir = from; ; dir = dirname(dir)) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return candidate;
    if (dirname(dir) === dir) return null;
  }
}
function copyMatching(srcDir, destDir, re) {
  if (!srcDir || !existsSync(srcDir)) return 0;
  mkdirSync(destDir, { recursive: true });
  let n = 0;
  for (const f of readdirSync(srcDir)) if (re.test(f)) { copyFileSync(join(srcDir, f), join(destDir, f)); n++; }
  return n;
}

// 1. ONNX Runtime Web for the core intent classifier (plain WASM build, single-threaded use).
const ort = pkgDir("onnxruntime-web");
log(`ort: ${copyMatching(ort && join(ort, "dist"), pub("ort"), /^ort-wasm-simd-threaded\.(wasm|mjs)$/)} files`);

// 2. The onnxruntime-web copy that Transformers.js depends on (may be a different version).
const tf = pkgDir("@huggingface/transformers");
const tfOrt = tf && (pkgDir("onnxruntime-web", tf) || ort);
log(`ort-tf: ${copyMatching(tfOrt && join(tfOrt, "dist"), pub("ort-tf"), /^ort-wasm-simd-threaded.*\.(wasm|mjs)$/)} files`);

// 3. Tesseract.js worker + LSTM-only WASM cores (we run OEM 1 = LSTM).
const tjs = pkgDir("tesseract.js");
const tcore = pkgDir("tesseract.js-core", tjs || root);
log(`tesseract worker: ${copyMatching(tjs && join(tjs, "dist"), pub("tesseract"), /^worker\.min\.js$/)} files`);
log(`tesseract core: ${copyMatching(tcore, pub("tesseract", "core"), /^tesseract-core.*lstm\.wasm\.js$/)} files`);

// 4. English OCR language data (tessdata "best_int"), from the @tesseract.js-data/eng package.
const engPkg = pkgDir("@tesseract.js-data/eng");
const engSrc = engPkg && join(engPkg, "4.0.0_best_int", "eng.traineddata.gz");
if (engSrc && existsSync(engSrc)) {
  mkdirSync(pub("tesseract", "lang"), { recursive: true });
  copyFileSync(engSrc, pub("tesseract", "lang", "eng.traineddata.gz"));
  log(`tesseract lang: eng (${(statSync(engSrc).size / 1e6).toFixed(1)} MB)`);
} else {
  log("WARNING: @tesseract.js-data/eng not installed — offline OCR will not work.");
}

// 5. Self-contained Transformers.js build for the speech worker (public/asr-worker.js). Workers are
//    plain files (not bundled) because the bundler's module-worker support breaks in static exports.
const tfMin = tf && join(tf, "dist", "transformers.min.js");
if (tfMin && existsSync(tfMin)) {
  mkdirSync(pub("vendor"), { recursive: true });
  copyFileSync(tfMin, pub("vendor", "transformers.min.js"));
  log(`vendor: transformers.min.js (${(statSync(tfMin).size / 1e3).toFixed(0)} kB)`);
}

writeFileSync(pub("RUNTIME_ASSETS.txt"), "Generated by scripts/copy-runtime-assets.mjs — do not edit or commit.\n");
