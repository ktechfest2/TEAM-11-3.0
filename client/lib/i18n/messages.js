export const MESSAGES = { en, pcm, yo, ha, ig };
export const SOURCE_MESSAGES = en; // the text translators work from

/** Approved translations fetched from the server (see AppProvider); they take precedence. */
const contributed = {};
export function setContributedMessages(lang, messages) {
  contributed[lang] = messages || {};
}

export function translate(lang, key, vars = {}) {
  const s = contributed[lang]?.[key] ?? MESSAGES[lang]?.[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
